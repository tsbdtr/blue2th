// Criterion (certificate): self-signed by the key — issuer is subject, the
// signature verifies against its own public key, and that key is ours.
#[test]
fn test_issue_certificate_is_self_signed_by_the_key() {
    let key = p256();
    let cert = issue_certificate(&key, Some(lan()), NAME, t0()).expect("issue");
    let parsed = x509_parser::parse_x509_certificate(&cert.der).map(|(_, c)| c);
    assert!(parsed.is_ok(), "the issued DER parses");
    let parsed = parsed.ok();
    assert_eq!(
        parsed.as_ref().map(|c| c.issuer() == c.subject()),
        Some(true),
        "issuer and subject are the same name"
    );
    assert_eq!(
        parsed.as_ref().map(|c| c.verify_signature(None).is_ok()),
        Some(true),
        "the signature verifies against the certificate's own key"
    );
    assert_eq!(
        parsed.as_ref().map(|c| c.public_key().raw.to_vec()),
        Some(key.subject_public_key_info()),
        "the certified key is the stored key"
    );
}

