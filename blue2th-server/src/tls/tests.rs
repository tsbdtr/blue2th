// Criterion (certificate): an expired certificate is reissued at any `now`,
// including one so late that `now + 30 days` no longer fits in a
// `SystemTime`. Near-miss: an expiry check written as `now.checked_add(30
// days)?` answers `None` there, which reads as "reuse".
#[test]
fn test_reissue_reason_an_expired_certificate_reissues_even_at_the_end_of_time() {
    let late = SystemTime::UNIX_EPOCH.checked_add(Duration::from_secs(i64::MAX as u64) - DAY);
    assert!(late.is_some(), "this platform represents the instant");
    assert!(
        late.and_then(|t| t.checked_add(30 * DAY)).is_none(),
        "the fixture is the overflow case"
    );
    let stored = healthy();
    assert_eq!(
        late.and_then(|now| reissue_reason(Some(&stored), SPKI, Some(lan()), NAME, now)),
        Some(ReissueReason::ExpiringSoon)
    );
}

// Criterion (certificate): every reissue logs its reason and that the browser
// will warn again. Each reason reads differently, so the log says which.
#[test]
fn test_reissue_message_names_the_reason_and_the_browser_warning() {
    let reasons = [
        ReissueReason::Unusable,
        ReissueReason::IpChanged,
        ReissueReason::NameChanged,
        ReissueReason::KeyChanged,
        ReissueReason::ExpiringSoon,
        ReissueReason::NotYetValid,
    ];
    let mut shown: Vec<String> = reasons.iter().map(ToString::to_string).collect();
    for (reason, text) in reasons.iter().zip(&shown) {
        assert!(!text.is_empty(), "{reason:?} has no text");
        let message = reissue_message(*reason);
        assert!(
            message.contains(text.as_str()),
            "{reason:?}: got {message:?}"
        );
        assert!(
            message.contains("browser") && message.contains("warn"),
            "{reason:?}: the message says the browser will warn again, got {message:?}"
        );
    }
    shown.sort();
    shown.dedup();
    assert_eq!(
        shown.len(),
        reasons.len(),
        "two reasons read the same: {shown:?}"
    );
}

// ---- issue_certificate / parse_cert_facts ----

/// The subject alternative names of a DER certificate, as `ip:` / `dns:` text.
fn sans_of(der: &[u8]) -> Vec<String> {
    let parsed = x509_parser::parse_x509_certificate(der).map(|(_, c)| c);
    assert!(parsed.is_ok(), "the issued DER parses");
    let mut sans: Vec<String> = parsed
        .ok()
        .and_then(|cert| {
            cert.subject_alternative_name().ok().flatten().map(|ext| {
                ext.value
                    .general_names
                    .iter()
                    .map(|name| match name {
                        GeneralName::DNSName(dns) => format!("dns:{dns}"),
                        GeneralName::IPAddress(bytes) => format!("ip:{bytes:?}"),
                        other => format!("other:{other:?}"),
                    })
                    .collect()
            })
        })
        .unwrap_or_default();
    sans.sort();
    sans
}

// Criterion (certificate): the SANs are exactly the advertised IP and
// `<label>.local` — no `localhost`, no `127.0.0.1`.
#[test]
fn test_issue_certificate_carries_exactly_the_ip_and_the_local_name() {
    let key = p256();
    let cert = issue_certificate(&key, Some(lan()), NAME, t0()).expect("issue");
    assert_eq!(
        sans_of(&cert.der),
        vec![
            format!("dns:{NAME}"),
            format!("ip:{:?}", [192u8, 168, 1, 20].as_slice()),
        ]
    );
}

