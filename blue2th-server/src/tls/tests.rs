// Criterion (fingerprint): 95 characters, 32 pairs, on a real certificate.
#[test]
fn test_certificate_fingerprint_of_a_certificate_has_the_browser_shape() {
    let key = p256();
    let cert = issue_certificate(&key, Some(lan()), NAME, t0()).expect("issue");
    let fingerprint = certificate_fingerprint(&cert.der);
    assert_eq!(fingerprint.len(), 95, "got {fingerprint:?}");
    let pairs: Vec<&str> = fingerprint.split(':').collect();
    assert_eq!(pairs.len(), 32, "got {fingerprint:?}");
    assert!(
        pairs.iter().all(|p| p.len() == 2
            && p.chars()
                .all(|c| c.is_ascii_digit() || ('A'..='F').contains(&c))),
        "upper-case hex pairs, got {fingerprint:?}"
    );
}

